def _rule_text(value: object, label: str) -> str:
    if not isinstance(value, str) or not value or "\x00" in value or "\n" in value or "\r" in value:
        raise RuleRenderError(f"{label} must be a non-empty string without a line break or NUL")
    return value


def _rule_bool(value: object, label: str) -> bool:
    if not isinstance(value, bool):
        raise RuleRenderError(f"{label} must be a boolean")
    return value


def _rule_positive_int(value: object, label: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value < 1:
        raise RuleRenderError(f"{label} must be a positive integer")
    return value


def _rule_quote(value: object, label: str) -> str:
    return '"' + _sway_quoted(_rule_text(value, label)) + '"'


def _render_border(border: object) -> str:
    if not isinstance(border, Mapping) or set(border) - {"style", "width"}:
        raise RuleRenderError("border must contain only style and optional width")
    style = border.get("style")
    if style not in {"none", "normal", "pixel"}:
        raise RuleRenderError("border style must be none, normal, or pixel")
    width = border.get("width")
    if width is not None:
        if isinstance(width, bool) or not isinstance(width, int) or width < 0:
            raise RuleRenderError("border width must be a non-negative integer")
        if style == "none":
            raise RuleRenderError("border none cannot have a width")
    if style == "pixel" and width is None:
        raise RuleRenderError("border pixel requires a width")
    return f"border {style}" + (f" {width}" if width is not None else "")


def _workspace_destination(name: object) -> str:
    """Render a workspace target as a Sway ``assign``/``move`` operand.

    Numeric names use the ``number`` form so Sway treats them as numbered
    workspaces; everything else stays a quoted name.
    """

    text = _rule_text(name, "destination workspace")
    if text.isdigit() and int(text) > 0:
        return "number " + text
    return _rule_quote(text, "destination workspace")


def render_window_rule(rule: Mapping[str, Any]) -> str:
    """Render one bounded window rule; require a matcher and visible outcome.

    A workspace destination becomes an ``assign`` statement because
    ``for_window ... move container to workspace`` is undone often enough in Sway
    1.9 that new windows regularly stay on the focused workspace.  Centering a
    floating container re-parents it to the focused workspace, so when both a
    destination and ``center`` are requested the destination move is re-issued as
    the final statement of the ``for_window`` body.
    """

    if not isinstance(rule, Mapping):
        raise RuleRenderError("window rule must be an object")
    match = rule.get("match")
    if not isinstance(match, Mapping):
        raise RuleRenderError("window rule requires match")
    try:
        criteria = render_criteria(match)
    except CriteriaError as exc:
        raise RuleRenderError(str(exc)) from exc
    destination = rule.get("destination", {})
    effects = rule.get("effects", {})
    if not isinstance(destination, Mapping) or set(destination) - {"workspace", "output"}:
        raise RuleRenderError("window destination can contain only workspace or output")
    if len(destination) > 1:
        raise RuleRenderError("window destination must choose workspace or output, not both")
    if not isinstance(effects, Mapping):
        raise RuleRenderError("window effects must be an object")
    supported_effects = {
        "floating", "width_px", "height_px", "center", "fullscreen", "sticky", "no_focus", "border", "opacity"
    }
    unknown = set(effects) - supported_effects
    if unknown:
        raise RuleRenderError(f"unsupported window effect: {sorted(unknown)[0]}")

    assignment: str | None = None
    destination_move: str | None = None
    if "workspace" in destination:
        target = _workspace_destination(destination["workspace"])
        assignment = f"assign {criteria} workspace {target}"
        destination_move = f"move container to workspace {target}"
    elif "output" in destination:
        destination_move = "move container to output " + _rule_quote(destination["output"], "destination output")

    commands: list[str] = []
    for name, command in (("floating", "floating"), ("fullscreen", "fullscreen"), ("sticky", "sticky")):
        if name in effects:
            commands.append(command + (" enable" if _rule_bool(effects[name], name) else " disable"))
    if "width_px" in effects:
        commands.append(f"resize set width {_rule_positive_int(effects['width_px'], 'width_px')} px")
    if "height_px" in effects:
        commands.append(f"resize set height {_rule_positive_int(effects['height_px'], 'height_px')} px")
    if "center" in effects and _rule_bool(effects["center"], "center"):
        commands.append("move position center")
    if destination_move is not None:
        # Re-assert the destination after any centering so the placement survives.
        commands.append(destination_move)
    if "no_focus" in effects and _rule_bool(effects["no_focus"], "no_focus"):
        commands.append("no_focus")
    if "border" in effects:
        commands.append(_render_border(effects["border"]))
    if "opacity" in effects:
        opacity = effects["opacity"]
        if isinstance(opacity, bool) or not isinstance(opacity, (int, float)) or not math.isfinite(opacity) or not 0 <= opacity <= 1:
            raise RuleRenderError("opacity must be a finite number from 0 through 1")
        commands.append(f"opacity {opacity:g}")
    if not commands:
        raise RuleRenderError("window rule requires at least one effect or destination")
    statement = "for_window " + criteria + " " + ", ".join(commands)
    return statement if assignment is None else assignment + "\n" + statement


def render_workspace_output_rule(rule: Mapping[str, Any]) -> str:
    """Render a workspace-to-output assignment without any shell interpolation."""

    if not isinstance(rule, Mapping):
        raise RuleRenderError("workspace-output rule must be an object")
    if set(rule) - {"workspace", "outputs"}:
        raise RuleRenderError("workspace-output rule contains unsupported fields")
    workspace = _rule_quote(rule.get("workspace"), "workspace")
    outputs = rule.get("outputs")
    if isinstance(outputs, (str, bytes)) or not isinstance(outputs, (list, tuple)) or not outputs:
        raise RuleRenderError("outputs must be a non-empty list")
    rendered_outputs = [_rule_quote(output, "output") for output in outputs]
    if len(set(outputs)) != len(outputs):
        raise RuleRenderError("outputs must be unique")
    return "workspace " + workspace + " output " + " ".join(rendered_outputs)


def render_rule(rule: Mapping[str, Any]) -> str:
    """Dispatch a typed persistent rule to its one supported Sway statement."""

    if not isinstance(rule, Mapping):
        raise RuleRenderError("rule must be an object")
    kind = rule.get("kind")
    payload = {key: value for key, value in rule.items() if key != "kind"}
    if kind == "window":
        return render_window_rule(payload)
    if kind == "workspace_output":
        return render_workspace_output_rule(payload)
    raise RuleRenderError("rule kind must be window or workspace_output")


def audit_cardinality(
    match: Mapping[str, Any], intended: str, windows: list[Mapping[str, Any]] | tuple[Mapping[str, Any], ...], *, require_verified: bool = False
) -> CardinalityAudit:
    """Audit declarative matching against supplied current-window snapshots."""

    if intended not in {"one", "many"}:
        raise CardinalityError("intended cardinality must be one or many")
    # Validate exactly the same matcher accepted by the renderer before use.
    render_criteria(match)
    matched: list[int] = []
    for index, window in enumerate(windows):
        if not isinstance(window, Mapping):
            raise CardinalityError("window snapshots must be objects")
        matched_window = True
        for key, specification in match.items():
            value = window.get(key)
            expected = specification if isinstance(specification, str) else specification.get("value")
            mode = "exact" if isinstance(specification, str) else specification.get("mode", "exact")
            if not isinstance(value, str) or not isinstance(expected, str):
                matched_window = False
                break
            if mode == "exact" and value != expected:
                matched_window = False
                break
            if mode == "regex":
                try:
                    if re.search(expected, value) is None:
                        matched_window = False
                        break
                except re.error as exc:
                    raise CardinalityError(f"invalid regex for {key}: {exc}") from exc
        if matched_window:
            matched.append(index)
    count = len(matched)
    verified = count == 1 if intended == "one" else count >= 1
    audit = CardinalityAudit(intended, count, tuple(matched), verified)
    if require_verified and not verified:
        expectation = "one" if intended == "one" else "one or more"
        raise CardinalityError(f"expected {expectation} matching current window(s), found {count}")
    return audit



_RULE_CONFIG_NAME = "hermes-sway-plugin-rules.conf"
_RULE_MAIN_CONFIG_NAME = "config"
_RULE_FORMAT = 1
_RULE_ID = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.:-]{0,63}$")


@dataclass(frozen=True)
class ManagedRulePaths:
    """Explicit configured locations used by the plugin-owned rule include."""

    config_dir: Path
    main_config: Path
    include: Path


def resolve_managed_config_dir(config_dir: str | Path | None) -> tuple[Path, Path]:
    """Resolve the owned include directory and the Sway configuration it augments.

    An explicit ``config_dir`` names the Sway configuration directory to manage,
    so the owned include lives beside that configuration.  An empty setting uses
    the documented XDG default: includes under
    ``${XDG_CONFIG_HOME:-~/.config}/sway/hermes`` and the main configuration at
    ``${XDG_CONFIG_HOME:-~/.config}/sway/config``.  The plugin never edits that
    main configuration; it only reads it and requires the exact include line.
    """

    if config_dir in (None, ""):
        base = (os.environ.get("XDG_CONFIG_HOME") or "").strip()
        root = Path(base).expanduser() if base else Path.home() / ".config"
        sway_home = root / "sway"
        return sway_home / "hermes", sway_home / "config"
    if not isinstance(config_dir, (str, Path)):
        raise ConfigFormatError("config_dir must be a string or path")
    directory = Path(config_dir).expanduser()
    if not directory.is_absolute():
        raise ConfigFormatError("config_dir must be an absolute path")
    return directory, directory / _RULE_MAIN_CONFIG_NAME


def managed_rule_paths(config_dir: str | Path | None) -> ManagedRulePaths:
    """Resolve the owned rule include beside the Sway configuration it augments."""

    directory, main_config = resolve_managed_config_dir(config_dir)
    return ManagedRulePaths(directory, main_config, directory / _RULE_CONFIG_NAME)


def _copy_json(value: Any) -> Any:
    """Copy only JSON-safe resource values and expose deterministic representations."""

    try:
        return json.loads(json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")))
    except (TypeError, ValueError) as exc:
        raise RuleRenderError("rule must contain JSON-compatible values") from exc


def _rule_id(value: object, *, rule: Mapping[str, Any] | None = None) -> str:
    if value is None:
        if rule is None:
            raise RuleRenderError("rule_id is required")
        digest = hashlib.sha256(_canonical_metadata(rule).encode("utf-8")).hexdigest()[:16]
        return "rule-" + digest
    if not isinstance(value, str) or not _RULE_ID.fullmatch(value):
        raise RuleRenderError("rule_id must use 1-64 letters, numbers, '.', '_', ':', or '-'")
    return value


def normalize_managed_rule(rule: Mapping[str, Any], *, allow_generated_id: bool = True) -> dict[str, Any]:
    """Validate, render, and canonicalize one persisted resource entry."""

    if not isinstance(rule, Mapping):
        raise RuleRenderError("rule entry must be an object")
    kind = rule.get("kind")
    if kind == "window":
        intended = rule.get("intended_cardinality")
        if intended not in {"one", "many"}:
            raise RuleRenderError("window rule requires intended_cardinality one or many")
        candidate = {
            "kind": "window",
            "match": _copy_json(rule.get("match")),
            "destination": _copy_json(rule.get("destination", {})),
            "effects": _copy_json(rule.get("effects", {})),
            "intended_cardinality": intended,
        }
    elif kind == "workspace_output":
        candidate = {
            "kind": "workspace_output",
            "workspace": _copy_json(rule.get("workspace")),
            "outputs": _copy_json(rule.get("outputs")),
        }
    else:
        raise RuleRenderError("rule kind must be window or workspace_output")
    # Rendering is also the complete grammar and bounded-effects validation.
    render_rule(candidate)
    rule_id = _rule_id(rule.get("rule_id"), rule=candidate if allow_generated_id else None)
    return {"rule_id": rule_id, **candidate}


def render_managed_rules(rules: tuple[Mapping[str, Any], ...] | list[Mapping[str, Any]]) -> str:
    """Render sorted resource entries into the one deterministic managed document."""

    normalized = [normalize_managed_rule(rule, allow_generated_id=False) for rule in rules]
    if len({rule["rule_id"] for rule in normalized}) != len(normalized):
        raise ConfigFormatError("managed rule metadata contains duplicate rule_id values")
    ordered = sorted(normalized, key=lambda rule: rule["rule_id"])
    body = "".join(render_rule({key: value for key, value in rule.items() if key not in {"rule_id", "intended_cardinality"}}) + "\n" for rule in ordered)
    metadata = {"format": _RULE_FORMAT, "resource": "sway_rule", "rules": ordered}
    return render_managed_config(body, metadata)


class ManagedRuleStore:
    """Stdlib-only managed resource facade for plugin-owned Sway rules."""

    def __init__(self, config_dir: str | Path) -> None:
        self.paths = managed_rule_paths(config_dir)

    def list(self) -> list[dict[str, Any]]:
        include = self.paths.include
        if not include.exists():
            return []
        try:
            parsed = parse_managed_config(include.read_text(encoding="utf-8"))
        except OSError as exc:
            raise ConfigFormatError(f"cannot read managed rule include: {exc}") from exc
        metadata = parsed.metadata
        if set(metadata) != {"format", "resource", "rules"} or metadata.get("format") != _RULE_FORMAT or metadata.get("resource") != "sway_rule":
            raise ConfigFormatError("managed rule include has unrecognized metadata")
        rules = metadata.get("rules")
        if not isinstance(rules, list):
            raise ConfigFormatError("managed rule metadata must contain a rules list")
        rendered = render_managed_rules(rules)
        expected = parse_managed_config(rendered)
        if expected.body != parsed.body:
            raise ManualEditRefused("manual edit refused: managed rules do not match metadata")
        return [_copy_json(rule) for rule in expected.metadata["rules"]]

    def get(self, rule_id: object) -> dict[str, Any]:
        selected = _rule_id(rule_id)
        for rule in self.list():
            if rule["rule_id"] == selected:
                return rule
        raise ConfigFormatError(f"managed rule not found: {selected}")

    def preview(self, rules: list[Mapping[str, Any]]) -> str:
        return render_managed_rules(rules)

    def write(
        self,
        rules: list[Mapping[str, Any]],
        *,
        subprocess_run: Callable[..., Any],
        atomic_replace_fn: Callable[..., AtomicWrite] | None = None,
        backup_count: int = 3,
        sway_binary: str = "sway",
    ) -> AtomicWrite:
        if isinstance(backup_count, bool) or not isinstance(backup_count, int) or backup_count < 0:
            raise AtomicWriteError("backup_keep must be a non-negative integer")
        if not self.paths.main_config.is_file():
            raise ConfigValidationError(f"configuration does not exist: {self.paths.main_config}")
        content = render_managed_rules(rules)
        self.paths.config_dir.mkdir(parents=True, exist_ok=True)
        return write_managed_include(
            self.paths.include,
            self.paths.main_config,
            content,
            subprocess_run=subprocess_run,
            atomic_replace_fn=atomic_replace_fn,
            backup_count=backup_count,
            sway_binary=sway_binary,
        )

    def _conflicts(self, new_rule: Mapping[str, Any]) -> tuple[IncludeConflict, ...]:
        """Refuse competing *external* rule statements unless explicitly allowed.

        The plugin-owned includes are never external: their statements are managed
        by this store, and the include lines themselves are configuration the user
        was instructed to add.
        """

        return scan_include_conflicts(
            self.paths.main_config,
            managed_include=self.paths.include,
            owned_includes=(self.paths.config_dir / _STARTUP_CONFIG_NAME,),
        )

    def add(self, rule: Mapping[str, Any], **write_kwargs: Any) -> dict[str, Any]:
        created = normalize_managed_rule(rule)
        existing = self.list()
        if any(entry["rule_id"] == created["rule_id"] for entry in existing):
            raise ConfigFormatError(f"managed rule already exists: {created['rule_id']}")
        self.write(existing + [created], **write_kwargs)
        return created

    def update(self, rule_id: object, rule: Mapping[str, Any], **write_kwargs: Any) -> dict[str, Any]:
        selected = _rule_id(rule_id)
        updated = normalize_managed_rule({**dict(rule), "rule_id": selected}, allow_generated_id=False)
        existing = self.list()
        if not any(entry["rule_id"] == selected for entry in existing):
            raise ConfigFormatError(f"managed rule not found: {selected}")
        self.write([updated if entry["rule_id"] == selected else entry for entry in existing], **write_kwargs)
        return updated

    def remove(self, rule_id: object, **write_kwargs: Any) -> dict[str, Any]:
        removed = self.get(rule_id)
        self.write([entry for entry in self.list() if entry["rule_id"] != removed["rule_id"]], **write_kwargs)
        return removed


