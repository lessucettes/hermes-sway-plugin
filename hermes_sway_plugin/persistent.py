_MANAGED_MARKER = "# hermes-sway-plugin: managed-v1"
_METADATA_PREFIX = "# hermes-sway-plugin: metadata="
_DIGEST_PREFIX = "# hermes-sway-plugin: sha256="


class PersistentConfigError(Exception):
    """Base failure for a plugin-owned configuration operation."""


class ConfigFormatError(PersistentConfigError):
    """The include is not a complete managed include."""


class ManualEditRefused(PersistentConfigError):
    """The managed body differs from the body last generated by the plugin."""


class CriteriaError(PersistentConfigError):
    """A declarative window matcher cannot be represented safely by Sway."""


class RuleRenderError(PersistentConfigError):
    """A persistent rule is incomplete or cannot be rendered safely."""


class CardinalityError(PersistentConfigError):
    """The current desktop cannot verify a rule's intended cardinality."""


class ConfigValidationError(PersistentConfigError):
    """Sway rejected a candidate or main configuration in check-only mode."""


class AtomicWriteError(PersistentConfigError):
    """A managed include could not be safely committed to disk."""


class ReloadRollbackError(PersistentConfigError):
    """Sway did not confirm a reload and restoration could not be confirmed."""


class DuplicateStartupEntry(PersistentConfigError):
    """A managed startup command duplicates an existing normalized command."""


