"""Pure, stdlib-only building blocks for plugin-owned Sway configuration.

The module deliberately has no knowledge of model handlers or user configuration
locations.  Callers supply every path and every side-effecting dependency.
"""

from __future__ import annotations

from dataclasses import dataclass
import hashlib
import json
import math
import re
from collections.abc import Mapping
from pathlib import Path
from typing import Any

_MANAGED_MARKER = "# hermes-sway-plugin: managed-v1"
_METADATA_PREFIX = "# hermes-sway-plugin: metadata="
_DIGEST_PREFIX = "# hermes-sway-plugin: sha256="


class PersistentConfigError(Exception):
    """Base failure for a plugin-owned configuration operation."""


class ConfigFormatError(PersistentConfigError):
    """The include is not a complete managed include."""


class ManualEditRefused(PersistentConfigError):
    """The managed body differs from the body last generated by the plugin."""


class CriteriaError(PersistentConfigError):
    """A declarative window matcher cannot be represented safely by Sway."""


class RuleRenderError(PersistentConfigError):
    """A persistent rule is incomplete or cannot be rendered safely."""


class CardinalityError(PersistentConfigError):
    """The current desktop cannot verify a rule's intended cardinality."""


@dataclass(frozen=True)
class IncludeConflict:
    kind: str
    source: Path
    line: int
    text: str


@dataclass(frozen=True)
class ManagedConfig:
    """The verified metadata and Sway body from one managed include."""

    metadata: dict[str, Any]
    body: str
    digest: str


@dataclass(frozen=True)
class CardinalityAudit:
    intended: str
    match_count: int
    matched_indices: tuple[int, ...]
    verified: bool


def _canonical_metadata(metadata: Mapping[str, Any]) -> str:
    if not isinstance(metadata, Mapping):
        raise ConfigFormatError("managed metadata must be an object")
    try:
        return json.dumps(dict(metadata), ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    except (TypeError, ValueError) as exc:
        raise ConfigFormatError("managed metadata is not JSON serializable") from exc


def _body_digest(body: str) -> str:
    return hashlib.sha256(body.encode("utf-8")).hexdigest()


def render_managed_config(body: str, metadata: Mapping[str, Any]) -> str:
    """Render a deterministic, tamper-evident managed Sway include.

    The digest protects the emitted Sway body.  Metadata is canonical JSON so a
    future writer can safely compare it without depending on mapping order.
    """

    if not isinstance(body, str):
        raise ConfigFormatError("managed body must be a string")
    if "\x00" in body:
        raise ConfigFormatError("managed body cannot contain NUL")
    metadata_text = _canonical_metadata(metadata)
    return "\n".join(
        (
            _MANAGED_MARKER,
            _METADATA_PREFIX + metadata_text,
            _DIGEST_PREFIX + _body_digest(body),
            "",
            body,
        )
    )


def parse_managed_config(text: str) -> ManagedConfig:
    """Parse a renderer-produced include and refuse a manually changed body."""

    if not isinstance(text, str):
        raise ConfigFormatError("managed config must be text")
    header, separator, body = text.partition("\n\n")
    if not separator:
        raise ConfigFormatError("managed config is missing its header separator")
    lines = header.splitlines()
    if len(lines) != 3 or lines[0] != _MANAGED_MARKER:
        raise ConfigFormatError("managed config has an invalid header")
    if not lines[1].startswith(_METADATA_PREFIX) or not lines[2].startswith(_DIGEST_PREFIX):
        raise ConfigFormatError("managed config has an invalid metadata header")
    metadata_text = lines[1][len(_METADATA_PREFIX) :]
    try:
        metadata = json.loads(metadata_text)
    except json.JSONDecodeError as exc:
        raise ConfigFormatError("managed metadata is not valid JSON") from exc
    if not isinstance(metadata, dict) or _canonical_metadata(metadata) != metadata_text:
        raise ConfigFormatError("managed metadata is not canonical JSON object")
    digest = lines[2][len(_DIGEST_PREFIX) :]
    if len(digest) != 64 or any(char not in "0123456789abcdef" for char in digest):
        raise ConfigFormatError("managed config has an invalid sha256 digest")
    if _body_digest(body) != digest:
        raise ManualEditRefused("manual edit refused: managed Sway body checksum differs")
    return ManagedConfig(metadata=metadata, body=body, digest=digest)


# Short aliases keep the format API readable for callers which treat the include
# as a document rather than as a configuration object.
render_managed = render_managed_config
parse_managed = parse_managed_config


_CRITERIA_ORDER = (
    "app_id",
    "class",
    "instance",
    "title",
    "window_role",
    "window_type",
    "shell",
    "con_mark",
)
_CRITERIA_KEYS = frozenset(_CRITERIA_ORDER)
_PCRE_EXACT_SPECIALS = frozenset("\\.^$*+?{}[]|()")


def _escape_exact_pcre(value: str) -> str:
    return "".join("\\" + char if char in _PCRE_EXACT_SPECIALS else char for char in value)


def _sway_quoted(value: str) -> str:
    if "\x00" in value or "\n" in value or "\r" in value:
        raise CriteriaError("criterion value cannot contain a line break or NUL")
    return value.replace("\\", "\\\\").replace('"', '\\"')


def render_criteria(match: Mapping[str, Any]) -> str:
    """Render stable Sway criteria from explicit exact or regular-expression values.

    Exact text becomes an anchored PCRE expression.  ``regex`` deliberately
    leaves PCRE metacharacters intact, while both modes quote for Sway's config
    grammar rather than for a shell.
    """

    if not isinstance(match, Mapping) or not match:
        raise CriteriaError("at least one criterion is required")
    unknown = set(match) - _CRITERIA_KEYS
    if unknown:
        raise CriteriaError(f"unsupported criterion key: {sorted(unknown)[0]}")
    parts: list[str] = []
    for key in _CRITERIA_ORDER:
        if key not in match:
            continue
        specification = match[key]
        if isinstance(specification, str):
            value, mode = specification, "exact"
        elif isinstance(specification, Mapping):
            value = specification.get("value")
            mode = specification.get("mode", "exact")
            if set(specification) - {"value", "mode"}:
                raise CriteriaError(f"criterion {key} contains unsupported fields")
        else:
            raise CriteriaError(f"criterion {key} must be an object")
        if not isinstance(value, str) or not value:
            raise CriteriaError(f"criterion {key} value must be a non-empty string")
        if mode not in {"exact", "regex"}:
            raise CriteriaError(f"criterion {key} mode must be exact or regex")
        expression = "^" + _escape_exact_pcre(value) + "$" if mode == "exact" else value
        parts.append(f'{key}="{_sway_quoted(expression)}"')
    return "[" + " ".join(parts) + "]"


render_match_criteria = render_criteria


def _rule_text(value: object, label: str) -> str:
    if not isinstance(value, str) or not value or "\x00" in value or "\n" in value or "\r" in value:
        raise RuleRenderError(f"{label} must be a non-empty string without a line break or NUL")
    return value


def _rule_bool(value: object, label: str) -> bool:
    if not isinstance(value, bool):
        raise RuleRenderError(f"{label} must be a boolean")
    return value


def _rule_positive_int(value: object, label: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value < 1:
        raise RuleRenderError(f"{label} must be a positive integer")
    return value


def _rule_quote(value: object, label: str) -> str:
    return '"' + _sway_quoted(_rule_text(value, label)) + '"'


def _render_border(border: object) -> str:
    if not isinstance(border, Mapping) or set(border) - {"style", "width"}:
        raise RuleRenderError("border must contain only style and optional width")
    style = border.get("style")
    if style not in {"none", "normal", "pixel"}:
        raise RuleRenderError("border style must be none, normal, or pixel")
    width = border.get("width")
    if width is not None:
        if isinstance(width, bool) or not isinstance(width, int) or width < 0:
            raise RuleRenderError("border width must be a non-negative integer")
        if style == "none":
            raise RuleRenderError("border none cannot have a width")
    if style == "pixel" and width is None:
        raise RuleRenderError("border pixel requires a width")
    return f"border {style}" + (f" {width}" if width is not None else "")


def render_window_rule(rule: Mapping[str, Any]) -> str:
    """Render one bounded window rule; require a matcher and visible outcome."""

    if not isinstance(rule, Mapping):
        raise RuleRenderError("window rule must be an object")
    match = rule.get("match")
    if not isinstance(match, Mapping):
        raise RuleRenderError("window rule requires match")
    try:
        criteria = render_criteria(match)
    except CriteriaError as exc:
        raise RuleRenderError(str(exc)) from exc
    destination = rule.get("destination", {})
    effects = rule.get("effects", {})
    if not isinstance(destination, Mapping) or set(destination) - {"workspace"}:
        raise RuleRenderError("window destination can contain only workspace")
    if not isinstance(effects, Mapping):
        raise RuleRenderError("window effects must be an object")
    supported_effects = {
        "floating", "width_px", "height_px", "center", "fullscreen", "sticky", "no_focus", "border", "opacity"
    }
    unknown = set(effects) - supported_effects
    if unknown:
        raise RuleRenderError(f"unsupported window effect: {sorted(unknown)[0]}")
    commands: list[str] = []
    if "workspace" in destination:
        commands.append("move container to workspace " + _rule_quote(destination["workspace"], "destination workspace"))
    for name, command in (("floating", "floating"), ("fullscreen", "fullscreen"), ("sticky", "sticky")):
        if name in effects:
            commands.append(command + (" enable" if _rule_bool(effects[name], name) else " disable"))
    if "width_px" in effects:
        commands.append(f"resize set width {_rule_positive_int(effects['width_px'], 'width_px')} px")
    if "height_px" in effects:
        commands.append(f"resize set height {_rule_positive_int(effects['height_px'], 'height_px')} px")
    if "center" in effects and _rule_bool(effects["center"], "center"):
        commands.append("move position center")
    if "no_focus" in effects and _rule_bool(effects["no_focus"], "no_focus"):
        commands.append("no_focus")
    if "border" in effects:
        commands.append(_render_border(effects["border"]))
    if "opacity" in effects:
        opacity = effects["opacity"]
        if isinstance(opacity, bool) or not isinstance(opacity, (int, float)) or not math.isfinite(opacity) or not 0 <= opacity <= 1:
            raise RuleRenderError("opacity must be a finite number from 0 through 1")
        commands.append(f"opacity {opacity:g}")
    if not commands:
        raise RuleRenderError("window rule requires at least one effect or destination")
    return "for_window " + criteria + " " + ", ".join(commands)


def render_workspace_output_rule(rule: Mapping[str, Any]) -> str:
    """Render a workspace-to-output assignment without any shell interpolation."""

    if not isinstance(rule, Mapping):
        raise RuleRenderError("workspace-output rule must be an object")
    if set(rule) - {"workspace", "outputs"}:
        raise RuleRenderError("workspace-output rule contains unsupported fields")
    workspace = _rule_quote(rule.get("workspace"), "workspace")
    outputs = rule.get("outputs")
    if isinstance(outputs, (str, bytes)) or not isinstance(outputs, (list, tuple)) or not outputs:
        raise RuleRenderError("outputs must be a non-empty list")
    rendered_outputs = [_rule_quote(output, "output") for output in outputs]
    if len(set(outputs)) != len(outputs):
        raise RuleRenderError("outputs must be unique")
    return "workspace " + workspace + " output " + " ".join(rendered_outputs)


def render_rule(rule: Mapping[str, Any]) -> str:
    """Dispatch a typed persistent rule to its one supported Sway statement."""

    if not isinstance(rule, Mapping):
        raise RuleRenderError("rule must be an object")
    kind = rule.get("kind")
    payload = {key: value for key, value in rule.items() if key != "kind"}
    if kind == "window":
        return render_window_rule(payload)
    if kind == "workspace_output":
        return render_workspace_output_rule(payload)
    raise RuleRenderError("rule kind must be window or workspace_output")


def audit_cardinality(
    match: Mapping[str, Any], intended: str, windows: list[Mapping[str, Any]] | tuple[Mapping[str, Any], ...], *, require_verified: bool = False
) -> CardinalityAudit:
    """Audit declarative matching against supplied current-window snapshots."""

    if intended not in {"one", "many"}:
        raise CardinalityError("intended cardinality must be one or many")
    # Validate exactly the same matcher accepted by the renderer before use.
    render_criteria(match)
    matched: list[int] = []
    for index, window in enumerate(windows):
        if not isinstance(window, Mapping):
            raise CardinalityError("window snapshots must be objects")
        matched_window = True
        for key, specification in match.items():
            value = window.get(key)
            expected = specification if isinstance(specification, str) else specification.get("value")
            mode = "exact" if isinstance(specification, str) else specification.get("mode", "exact")
            if not isinstance(value, str) or not isinstance(expected, str):
                matched_window = False
                break
            if mode == "exact" and value != expected:
                matched_window = False
                break
            if mode == "regex":
                try:
                    if re.search(expected, value) is None:
                        matched_window = False
                        break
                except re.error as exc:
                    raise CardinalityError(f"invalid regex for {key}: {exc}") from exc
        if matched_window:
            matched.append(index)
    count = len(matched)
    verified = count == 1 if intended == "one" else count >= 1
    audit = CardinalityAudit(intended, count, tuple(matched), verified)
    if require_verified and not verified:
        expectation = "one" if intended == "one" else "one or more"
        raise CardinalityError(f"expected {expectation} matching current window(s), found {count}")
    return audit


def scan_include_conflicts(main_config: str | Path, *, managed_include: str | Path) -> tuple[IncludeConflict, ...]:
    """Conservatively scan literal includes without invoking a shell or Sway.

    Variable/glob/absolute includes are reported as unscannable rather than
    expanded.  The plugin-owned include itself is intentionally not inspected.
    """

    root = Path(main_config)
    owned = Path(managed_include).resolve()
    found: list[IncludeConflict] = []
    visited: set[Path] = set()

    def visit(path: Path) -> None:
        path = path.resolve()
        if path in visited or path == owned:
            return
        visited.add(path)
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except OSError:
            found.append(IncludeConflict("unreadable_include", path, 0, str(path)))
            return
        for number, raw in enumerate(lines, 1):
            statement = raw.strip()
            if not statement or statement.startswith("#"):
                continue
            lowered = statement.casefold()
            if lowered.startswith("for_window "):
                found.append(IncludeConflict("for_window", path, number, raw))
            elif lowered.startswith("assign ") or lowered.startswith("workspace ") and " output " in lowered:
                found.append(IncludeConflict("workspace_output", path, number, raw))
            if not lowered.startswith("include "):
                continue
            target = statement[8:].strip()
            if not target or target.startswith("/") or any(token in target for token in ("$", "~", "*", "?", "[", "]")):
                found.append(IncludeConflict("unscannable_include", path, number, raw))
                continue
            candidate = (path.parent / target).resolve()
            if candidate == owned:
                continue
            visit(candidate)

    visit(root)
    return tuple(found)
